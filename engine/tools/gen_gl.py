#!/usr/bin/env python3
"""Generates src/shims_gl.cpp: guest (32-bit) OpenGL ES 2 calls -> the phone's real GLES2.

Signature letters: e/u/i = 32-bit int, b = boolean, f = float (soft-float: bits in a core register),
z = GLsizeiptr (32-bit in the guest), p = guest pointer (translated, 0 stays NULL),
P = pointer-or-buffer-offset (glVertexAttribPointer: offset when a VBO is bound).
Return: v = void, i = int/uint, s = string (copied into guest memory).
"""
import sys

GL2 = """
v glActiveTexture e
v glAttachShader u u
v glBindFramebuffer e u
v glBindRenderbuffer e u
v glBindTexture e u
v glBlendFunc e e
v glBufferData e z p e
i glCheckFramebufferStatus e
v glClear u
v glClearColor f f f f
v glClearDepthf f
v glClearStencil i
v glColorMask b b b b
v glCompileShader u
i glCreateProgram
i glCreateShader e
v glDeleteBuffers i p
v glDeleteFramebuffers i p
v glDeleteProgram u
v glDeleteRenderbuffers i p
v glDeleteShader u
v glDeleteTextures i p
v glDepthFunc e
v glDepthMask b
v glDepthRangef f f
v glDisable e
v glDisableVertexAttribArray u
v glDrawArrays e i i
v glEnable e
v glEnableVertexAttribArray u
v glFlush
v glFramebufferRenderbuffer e e e u
v glFramebufferTexture2D e e e u i
v glFrontFace e
v glGenBuffers i p
v glGenFramebuffers i p
v glGenRenderbuffers i p
v glGenTextures i p
v glGetActiveAttrib u u i p p p p
v glGetActiveUniform u u i p p p p
i glGetAttribLocation u p
i glGetError
v glGetFramebufferAttachmentParameteriv e e e p
v glGetIntegerv e p
v glGetProgramInfoLog u i p p
v glGetProgramiv u e p
v glGetShaderInfoLog u i p p
v glGetShaderiv u e p
i glGetUniformLocation u p
v glHint e e
v glLinkProgram u
v glPixelStorei e i
v glReadPixels i i i i e e p
v glRenderbufferStorage e e i i
v glScissor i i i i
v glStencilFunc e i u
v glStencilFuncSeparate e e i u
v glStencilMask u
v glStencilMaskSeparate e u
v glStencilOp e e e
v glStencilOpSeparate e e e e
v glTexImage2D e i i i i i e e p
v glTexParameterf e e f
v glTexParameteri e e i
v glUniform1f i f
v glUniform1fv i i p
v glUniform1i i i
v glUniform1iv i i p
v glUniform2fv i i p
v glUniform2iv i i p
v glUniform3fv i i p
v glUniform3iv i i p
v glUniform4fv i i p
v glUniform4iv i i p
v glUniformMatrix2fv i i b p
v glUniformMatrix3fv i i b p
v glUniformMatrix4fv i i b p
v glUseProgram u
v glVertexAttribPointer u i e b i P
v glViewport i i i i
"""
# GLES1 names that alias GLES2 core functions.
ALIASES = {
    "glBindFramebufferOES": "glBindFramebuffer", "glBindRenderbufferOES": "glBindRenderbuffer",
    "glCheckFramebufferStatusOES": "glCheckFramebufferStatus", "glDeleteFramebuffersOES": "glDeleteFramebuffers",
    "glDeleteRenderbuffersOES": "glDeleteRenderbuffers", "glFramebufferRenderbufferOES": "glFramebufferRenderbuffer",
    "glFramebufferTexture2DOES": "glFramebufferTexture2D", "glGenFramebuffersOES": "glGenFramebuffers",
    "glGenRenderbuffersOES": "glGenRenderbuffers", "glRenderbufferStorageOES": "glRenderbufferStorage",
    "glGetFramebufferAttachmentParameterivOES": "glGetFramebufferAttachmentParameteriv",
}
# Fixed-function GLES1 calls: the runner uses its GLES2 path, so these are harmless no-ops.
GL1_ONLY = """glAlphaFunc glClearColorx glColor4x glColorPointer glDisableClientState glEnableClientState glFogf
glFogfv glFrustumx glLightModelfv glLightf glLightfv glLightxv glLoadIdentity glLoadMatrixf glMaterialfv
glMaterialx glMaterialxv glMatrixMode glMultMatrixf glMultMatrixx glNormalPointer glPopMatrix glPushMatrix
glRotatex glScalex glShadeModel glTexCoordPointer glTexEnvi glTranslatex glVertexPointer""".split()

CTYPE = {"e": "GLenum", "u": "GLuint", "i": "GLint", "b": "GLboolean", "f": "GLfloat", "z": "GLsizeiptr"}

out = ["// GENERATED by engine/tools/gen_gl.py – do not edit by hand.",
       "#include \"shims_gl.h\"", "", "#include <GLES2/gl2.h>", "", "namespace po {", "",
       "// A translated guest pointer that converts to whatever pointer type each GL function wants.",
       "struct GPtr {", "    void *p;", "    template <typename T> operator T *() const { return static_cast<T *>(p); }", "};", "",
       "void register_gl_generated(Runtime &rt, GlState &st) {",
       "    auto P = [&rt](uint32_t a) { return GPtr{a ? static_cast<void *>(rt.mem.host(a)) : nullptr}; };",
       "    (void)st;"]
for line in GL2.strip().splitlines():
    parts = line.split()
    ret, name, args = parts[0], parts[1], parts[2:]
    exprs = []
    for idx, a in enumerate(args):
        if a == "f":
            exprs.append(f"c.argf({idx})")
        elif a == "p":
            exprs.append(f"P(c.arg({idx}))")
        elif a == "P":
            exprs.append(f"(st.array_buffer ? reinterpret_cast<const void *>(static_cast<uintptr_t>(c.arg({idx}))) : static_cast<const void *>(P(c.arg({idx}))))")
        elif a == "z":
            exprs.append(f"static_cast<GLsizeiptr>(static_cast<int32_t>(c.arg({idx})))")
        else:
            exprs.append(f"static_cast<{CTYPE[a]}>(c.arg({idx}))")
    call = f"::{name}({', '.join(exprs)})"
    body = f"c.ret(static_cast<uint32_t>({call}));" if ret == "i" else f"{call};"
    out.append(f'    rt.def("{name}", [&rt, &st, P](Cpu &c) {{ (void)P; {body} }});')
for alias, target in ALIASES.items():
    out.append(f'    rt.alias("{alias}", "{target}");')
for name in GL1_ONLY:
    out.append(f'    rt.def("{name}", [&rt](Cpu &) {{ gl1_warn(rt, "{name}"); }});')
out += ["}", "", "}  // namespace po", ""]
open(sys.argv[1] if len(sys.argv) > 1 else "src/shims_gl_generated.cpp", "w").write("\n".join(out))
